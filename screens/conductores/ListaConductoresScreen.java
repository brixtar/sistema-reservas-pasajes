    public static void cargar_tabla(){
        limpiarTabla(jtChoferes);
        Chofer chofer = new Chofer();
        Object [][] datos= chofer.verChoferes();
        String [] NombresColumnas = {"N°","NOMBRE"};
        if(datos.length==0){ 
            btnModificar.setEnabled(false);
            btnEliminar.setEnabled(false);
        } else{
        DefaultTableModel modelo = new DefaultTableModel(datos,NombresColumnas);
        DefaultTableCellRenderer cent = new DefaultTableCellRenderer();
        cent.setHorizontalAlignment(SwingConstants.CENTER);
        
        jtChoferes.setModel(modelo);
        jtChoferes.getColumnModel().getColumn(0).setCellRenderer(cent);
        jtChoferes.getColumnModel().getColumn(1).setCellRenderer(cent);   
        
        
        //ajustamos ancho de columna
         int[] anchos = {200,500};
        for( int i = 0; i < jtChoferes.getColumnCount(); i++) {
            jtChoferes.getColumnModel().getColumn(i).setPreferredWidth(anchos[i]);}
        }
        
        jtChoferes.getColumnModel().getColumn(0).setMaxWidth(0);
        jtChoferes.getColumnModel().getColumn(0).setMinWidth(0);
        jtChoferes.getTableHeader().getColumnModel().getColumn(0).setMaxWidth(0);
        jtChoferes.getTableHeader().getColumnModel().getColumn(0).setMinWidth(0);
    }
    
    public static void limpiarTabla(JTable tabla){
        try {
            DefaultTableModel modelo=(DefaultTableModel) tabla.getModel();
            int filas=tabla.getRowCount();
            for (int i = 0;filas>i; i++) {
                modelo.removeRow(0);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al limpiar la tabla.");
        }
    }

