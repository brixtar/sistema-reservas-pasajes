    private void jmEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jmEliminarActionPerformed
     int fila = jtChoferes.getSelectedRow();
     if(fila==-1){
         JOptionPane.showMessageDialog(rootPane, "No se seleccionó ninguna fila");
     } else {
        int reply = JOptionPane.showConfirmDialog(null,"¿Seguro que desea eliminar el Chofer?", "ATENCIÓN", JOptionPane.YES_NO_OPTION);
        if (reply == JOptionPane.YES_OPTION) {
            String choferes_id= jtChoferes.getValueAt(fila, 0).toString();
            String nombre = jtChoferes.getValueAt(fila, 1).toString();
            int estado =1;
            Chofer chofer = new Chofer(choferes_id, nombre, estado);
            chofer.eliminar();
            cargar_tabla();
        }
        else {
           System.out.println("No se eliminó el Chofer");
        }
     }
    }//GEN-LAST:event_jmEliminarActionPerformed

