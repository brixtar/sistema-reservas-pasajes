    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
       String chofer_id= jtfChofer_ID.getText();
       String nombre = jtfNombre.getText().toUpperCase();
       int estado =1;
       
       ValidacionesConductor funcion = new ValidacionesConductor();
       if(funcion.validarNombre(nombre)){
            Chofer chofer = new Chofer(chofer_id, nombre, estado);
            chofer.guardar();

            jtfNombre.setText("");
            this.dispose();
            ListaConductoresScreen.cargar_tabla();
            ListaConductoresScreen.btnEliminar.setEnabled(true);
            ListaConductoresScreen.btnModificar.setEnabled(true);
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

