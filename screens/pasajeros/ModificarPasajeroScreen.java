    public boolean esNumero(String cadena){
        if(cadena != null || !cadena.equals("")) {
        char[] characters = cadena.toCharArray();
        for (int i = 0; i < cadena.length(); i++) {
            if (characters[i] < 48 || characters[i] > 57)
                return false;
            }
        }
        return true;
    }

