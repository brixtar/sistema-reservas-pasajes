    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String pasajero_dni= jtfDNI.getText();
        String nombre = jtfNombre.getText().toUpperCase();
        String domicilio = jtfDomicilio.getText().toUpperCase();
        String telefono = jtfTelefono.getText().toUpperCase();
        String fecha_alta = fechabd.format(fecha_actual);
        String fecha_cumple="";
        int estado =1;
        try {
            fecha_cumple = fechabd.format(jdcFecha_Cumple.getDate());
  
            ValidacionesPasajeros funcion = new ValidacionesPasajeros();
        
            if(funcion.validarDomicilio(domicilio)&&funcion.validarDNI(pasajero_dni)&&funcion.validarNombre(nombre)&&funcion.validarTelefono(telefono)){
                        Pasajero pasajero = new Pasajero(pasajero_dni, nombre, domicilio,telefono,fecha_alta,fecha_cumple,estado);
                        pasajero.guardar();

                        jtfDNI.setText("");
                        jtfNombre.setText("");
                        jtfDomicilio.setText("");
                        jtfTelefono.setText("");
                        
                        this.dispose();
                        ListaPasajerosScreen.cargar_tabla();
                        ListaPasajerosScreen.btnEliminar.setEnabled(true);
                        ListaPasajerosScreen.btnModificar.setEnabled(true);
        }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,"la fecha ingresada no es válida","ERROR",0);
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

