    private void jmEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jmEliminarActionPerformed
        int fila = jtPasajeros.getSelectedRow();
        if(fila==-1){
            JOptionPane.showMessageDialog(rootPane, "No se seleccionó ninguna fila");
        } else {
            int reply = JOptionPane.showConfirmDialog(null,"¿Seguro que desea eliminar el Pasajero?", "ATENCIÓN", JOptionPane.YES_NO_OPTION);
            if (reply == JOptionPane.YES_OPTION) {
                String pasajero_dni= ListaPasajerosScreen.jtPasajeros.getValueAt(fila, 0).toString();
                String nombre= ListaPasajerosScreen.jtPasajeros.getValueAt(fila, 1).toString();
                String domicilio= ListaPasajerosScreen.jtPasajeros.getValueAt(fila, 2).toString();
                String telefono = ListaPasajerosScreen.jtPasajeros.getValueAt(fila, 3).toString();
                String fecha_alta_[]= ListaPasajerosScreen.jtPasajeros.getValueAt(fila, 4).toString().split("-");
                String fecha_alta= fecha_alta_[2]+"-"+fecha_alta_[1]+"-"+fecha_alta_[0];
                String fecha_cumple_[]= ListaPasajerosScreen.jtPasajeros.getValueAt(fila, 5).toString().split("-");
                String fecha_cumple= fecha_cumple_[2]+"-"+fecha_cumple_[1]+"-"+fecha_cumple_[0];
                int estado =1;

                Pasajero pasajero = new Pasajero(pasajero_dni, nombre, domicilio,telefono,fecha_alta,fecha_cumple, estado);
                pasajero.eliminar();
                cargar_tabla();
            }
            else {
               System.out.println("No se eliminó el Pasajero");
            }
        }
    }//GEN-LAST:event_jmEliminarActionPerformed

