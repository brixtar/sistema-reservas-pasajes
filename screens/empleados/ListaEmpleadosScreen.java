    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = jtEmpleados.getSelectedRow();
        if(fila==-1){
            JOptionPane.showMessageDialog(rootPane, "No se seleccionó ninguna fila");
        } else {
            int reply = JOptionPane.showConfirmDialog(null,"¿Seguro que desea eliminar el Empleado?", "ATENCIÓN", JOptionPane.YES_NO_OPTION);
            if (reply == JOptionPane.YES_OPTION) {
                String empleado_dni= ListaEmpleadosScreen.jtEmpleados.getValueAt(fila, 0).toString();
                String nombre= ListaEmpleadosScreen.jtEmpleados.getValueAt(fila, 1).toString();
                String clave= ListaEmpleadosScreen.jtEmpleados.getValueAt(fila, 2).toString();
                int estado =1;

                Empleado empleado = new Empleado(empleado_dni, nombre,clave,estado);
                empleado.eliminar();
                cargar_tabla();
            }
            else {
               System.out.println("No se eliminó el Pasajero");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed


