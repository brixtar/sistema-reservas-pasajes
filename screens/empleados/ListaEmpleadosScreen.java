    public static void cargar_tabla(){
        limpiarTabla(jtEmpleados);
        Empleado empleado = new Empleado();
        Object [][] datos= empleado.verEmpleados();
        String [] NombresColumnas = {"DNI","NOMBRE","CLAVE"};
        DefaultTableModel modelo = new DefaultTableModel(datos,NombresColumnas);
        DefaultTableCellRenderer cent = new DefaultTableCellRenderer();
        cent.setHorizontalAlignment(SwingConstants.CENTER);
        
        
        for(int i=0; i<jtEmpleados.getModel().getRowCount() ;i++){
            String fecha[]= jtEmpleados.getModel().getValueAt(i, 3).toString().split("-");
            jtEmpleados.getModel().setValueAt(fecha[2]+fecha[1]+fecha[0], i, 3);
        }
        
        jtEmpleados.setModel(modelo);
        jtEmpleados.getColumnModel().getColumn(0).setCellRenderer(cent);
        jtEmpleados.getColumnModel().getColumn(1).setCellRenderer(cent);
        jtEmpleados.getColumnModel().getColumn(2).setCellRenderer(cent);
        
        //ajustamos ancho de columna
         int[] anchos = {200,400,200};
        for( int i = 0; i < jtEmpleados.getColumnCount(); i++) {
         jtEmpleados.getColumnModel().getColumn(i).setPreferredWidth(anchos[i]);
        }
        
        
    }
    
    public static void limpiarTabla(JTable tabla){
        try {
            DefaultTableModel modelo=(DefaultTableModel) tabla.getModel();
            int filas=tabla.getRowCount();
            for (int i = 0;filas>i; i++) {
                modelo.removeRow(0);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al limpiar la tabla.");
        }
    }

