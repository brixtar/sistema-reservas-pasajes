    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed

       String empleado_dni= jtfDNI.getText();
       String nombre = jtfNombre.getText().toUpperCase();
       String clave = jtfClave.getText().toUpperCase();
       int estado =1;
       
       ValidacionesEmpleado funcion = new ValidacionesEmpleado();
       if(funcion.validarClave(clave)&&funcion.validarDNI(empleado_dni)&&funcion.validarNombre(nombre)){
            Empleado empleado = new Empleado(empleado_dni, nombre, clave, estado);
            empleado.modificar(old_dni);

            ListaEmpleadosScreen.cargar_tabla();
            this.dispose();
       }
    }//GEN-LAST:event_btnConfirmarActionPerformed

