    public static void cargartabla(){
        limpiarTabla(jtComisiones);
        Comision comision = new Comision();
        Object[][] datos= comision.verComisiones();
        String [] NombresColumnas = {"N°","FECHA","REMITENTE","DESTINATARIO","FORMA","MONTO","EMPLEADO"};
        if(datos.length==0){ 
            
        }
        else{
            DefaultTableModel modelo = new DefaultTableModel(datos,NombresColumnas);
            DefaultTableCellRenderer cent = new DefaultTableCellRenderer();
            cent.setHorizontalAlignment(SwingConstants.CENTER);
        
            jtComisiones.setModel(modelo);
            jtComisiones.getColumnModel().getColumn(0).setCellRenderer(cent);
            jtComisiones.getColumnModel().getColumn(1).setCellRenderer(cent);
            jtComisiones.getColumnModel().getColumn(2).setCellRenderer(cent);
            jtComisiones.getColumnModel().getColumn(3).setCellRenderer(cent);
            jtComisiones.getColumnModel().getColumn(4).setCellRenderer(cent);
            jtComisiones.getColumnModel().getColumn(5).setCellRenderer(cent);
            jtComisiones.getColumnModel().getColumn(6).setCellRenderer(cent);
        
            for(int i=0; i<jtComisiones.getModel().getRowCount() ;i++){
              String fecha[]= jtComisiones.getModel().getValueAt(i, 1).toString().split("-");
              jtComisiones.getModel().setValueAt(fecha[2]+"-"+fecha[1]+"-"+fecha[0], i, 1);
              }
           
            //ajustamos ancho de columna
            int[] anchos = {50,400,850,850,250,250,750};
            for( int i = 0; i < jtComisiones.getColumnCount(); i++) {
            jtComisiones.getColumnModel().getColumn(i).setPreferredWidth(anchos[i]);
            }
        }
    }
    
    public static void limpiarTabla(JTable tabla){
        try {
            DefaultTableModel modelo=(DefaultTableModel) tabla.getModel();
            int filas=tabla.getRowCount();
            for (int i = 0;filas>i; i++) {
                modelo.removeRow(0);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al limpiar la tabla.");
        }
    }
    
    public void buscar(String cadena){
        DefaultTableModel   dm = (DefaultTableModel) jtComisiones.getModel();
        TableRowSorter<DefaultTableModel> tr = new TableRowSorter<>(dm);
        jtComisiones.setRowSorter(tr);
        tr.setRowFilter(RowFilter.regexFilter(cadena,0,1,2,3,4,5,6));
    }

