    private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImprimirActionPerformed
        List lista = new ArrayList();
        for (int i = 0; i < jtComisiones.getRowCount(); i++) {
            ImprimirListaComisiones comisiones= new ImprimirListaComisiones(
                    jtComisiones.getValueAt(i, 0).toString(), 
                    jtComisiones.getValueAt(i, 2).toString() , 
                    jtComisiones.getValueAt(i, 3).toString(), 
                    jtComisiones.getValueAt(i, 5).toString(), 
                    jtComisiones.getValueAt(i, 4).toString(),
                    jtComisiones.getValueAt(i, 1).toString(),
                    jtComisiones.getValueAt(i, 6).toString()
            );
            lista.add(comisiones);
        }
        String texto = jtfBuscar.getText();
        Date date = new Date();
        SimpleDateFormat fechajava = new SimpleDateFormat("dd/MM/yyyy");
        String fecha = fechajava.format(date);

        try {

            JasperReport reporte = null;

            String path = "src\\reportes\\comisiones_lista.jasper";

            reporte = (JasperReport) JRLoader.loadObjectFromFile(path);

            JasperPrint jprint;

            Map parametros = new HashMap();
            parametros.put("fecha", fecha);
            parametros.put("texto", texto);

            jprint = JasperFillManager.fillReport(reporte, parametros, new JRBeanCollectionDataSource(lista));
            JasperViewer view = new JasperViewer(jprint, false);
            view.setDefaultCloseOperation(DISPOSE_ON_CLOSE);
            view.setVisible(true);
        } catch (JRException ex) {
            Logger.getLogger(PanelComisionesScreen.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnImprimirActionPerformed


