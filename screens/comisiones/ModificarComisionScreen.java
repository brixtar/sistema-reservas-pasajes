    private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImprimirActionPerformed
                try {
            
                String comision_id = jtfNumero.getText();
                String nombre = jtfNombre.getText().toUpperCase();
                String calle = jtfCalle.getText().toUpperCase();
                String localidad = jcLocalidad.getSelectedItem().toString();
                String nombre2 = jtfNombre2.getText().toUpperCase();
                String calle2 = jtfCalle2.getText().toUpperCase();
                String localidad2 = jcLocalidad2.getSelectedItem().toString();
                String observaciones = jtfObservaciones.getText().toUpperCase();
                int monto_num = Integer.parseInt(jtfMonto.getText());
                String monto = Integer.toString(monto_num);
                String forma = jcForma.getSelectedItem().toString();
                String fecha = fechabd.format(fecha_actual);
                String empleado_dni = MainScreen.empleado_dni;

                JasperReport reporte = null;

                String path = "src\\reportes\\comision.jasper";

                reporte = (JasperReport) JRLoader.loadObjectFromFile(path);

                JasperPrint jprint;

                Map parametros = new HashMap();
                parametros.put("comision_id", comision_id);
                parametros.put("nombre", nombre);
                parametros.put("nombre2", nombre2);
                parametros.put("calle", calle);
                parametros.put("calle2", calle2);
                parametros.put("localidad", localidad);
                parametros.put("localidad2", localidad2);
                parametros.put("monto", monto);
                parametros.put("observaciones", observaciones);
                if (forma.equals("A/C")) {
                    parametros.put("ac",monto);
                    parametros.put("cc","-");
                    parametros.put("ctdo","-");     
                    parametros.put("debe","-");
                } else {
                    if (forma.equals("C/C")) {
                        parametros.put("ac","-");
                        parametros.put("cc",monto);
                        parametros.put("ctdo","-");
                        parametros.put("debe","-");
                    } else {
                        if (forma.equals("CTDO")) {
                            parametros.put("ac","-");
                            parametros.put("cc","-");
                            parametros.put("ctdo",monto);
                            parametros.put("debe","-");
                        } else {
                            parametros.put("ac","-");
                            parametros.put("cc","-");
                            parametros.put("ctdo","-"); 
                            parametros.put("debe",monto);
                        }
                    }
                }
                parametros.put("fecha", fechajava.format(fecha_actual));

                jprint = JasperFillManager.fillReport(reporte, parametros);
                JasperViewer view = new JasperViewer(jprint, false);
                view.setDefaultCloseOperation(DISPOSE_ON_CLOSE);
                view.setVisible(true);
            } catch (JRException ex) {
                Logger.getLogger(NuevaComisionScreen.class.getName()).log(Level.SEVERE, null, ex);
                JOptionPane.showMessageDialog(rootPane, "No se pudo imprimir la comision", "ERROR", 0);
            }

    }//GEN-LAST:event_btnImprimirActionPerformed

