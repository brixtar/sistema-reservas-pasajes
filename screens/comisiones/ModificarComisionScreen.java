    public void buscarComision(){
        try {
            int fila = jtComisiones.getSelectedRow();
            String comision_id= jtComisiones.getValueAt(fila,0).toString();
            Comision comision= new Comision();
            comision.buscarComision(comision_id);
            jtfNumero.setText(comision.getComision_id());
            Date fecha = fechabd.parse(comision.getFecha().toString());
            jtfFecha.setText(fechajava.format(fecha));
            jtfNombre.setText(comision.getNombre());
            jtfCalle.setText(comision.getCalle());
            jcLocalidad.setSelectedItem(comision.getLocalidad());
            jtfNombre2.setText(comision.getNombre2());
            jtfCalle2.setText(comision.getCalle2());
            jcLocalidad2.setSelectedItem(comision.getLocalidad2());
            jtfMonto.setText(comision.getMonto());
            jcForma.setSelectedItem(comision.getForma());
            jtfObservaciones.setText(comision.getObservaciones());
        } catch (ParseException ex) {
            Logger.getLogger(ModificarComisionScreen.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

