    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
       String vehiculo_id= jtfVehiculo_ID.getText();
       String descripcion = jtfDescripcion.getText().toUpperCase();
       int asientos = (int) jspAsientos.getValue();
       int estado =1;
       
       ValidacionesVehiculos funcion = new ValidacionesVehiculos();
       if(funcion.validarNombre(descripcion)){
            Vehiculo vehiculo = new Vehiculo(vehiculo_id, descripcion, asientos, estado);
            vehiculo.guardar();
            
            jtfDescripcion.setText("");
            buscarultimovehiculo();
            
            ListaVehiculosScreen.cargar_tabla();
            ListaVehiculosScreen.btnEliminar.setEnabled(true);
            ListaVehiculosScreen.btnModificar.setEnabled(true);
            this.dispose();
       }
    }//GEN-LAST:event_btnConfirmarActionPerformed

