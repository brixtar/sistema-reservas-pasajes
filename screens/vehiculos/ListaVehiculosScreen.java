    public static void cargar_tabla(){
        limpiarTabla(jtVehiculos);
        Vehiculo vehiculo = new Vehiculo();
        Object [][] datos= vehiculo.verVehiculos();
        String [] NombresColumnas = {"N°","DESCRIPCIÓN","ASIENTOS"};
        if(datos.length==0){ 
            btnModificar.setEnabled(false);
            btnEliminar.setEnabled(false);
        } else{
        DefaultTableModel modelo = new DefaultTableModel(datos,NombresColumnas);
        DefaultTableCellRenderer cent = new DefaultTableCellRenderer();
        cent.setHorizontalAlignment(SwingConstants.CENTER);
        
        jtVehiculos.setModel(modelo);
        jtVehiculos.getColumnModel().getColumn(0).setCellRenderer(cent);
        jtVehiculos.getColumnModel().getColumn(1).setCellRenderer(cent);
        jtVehiculos.getColumnModel().getColumn(2).setCellRenderer(cent);   
        
        
        //ajustamos ancho de columna
         int[] anchos = {200,400,200};
        for( int i = 0; i < jtVehiculos.getColumnCount(); i++) {
            jtVehiculos.getColumnModel().getColumn(i).setPreferredWidth(anchos[i]);}
        }
        
        jtVehiculos.getColumnModel().getColumn(0).setMaxWidth(0);
        jtVehiculos.getColumnModel().getColumn(0).setMinWidth(0);
        jtVehiculos.getTableHeader().getColumnModel().getColumn(0).setMaxWidth(0);
        jtVehiculos.getTableHeader().getColumnModel().getColumn(0).setMinWidth(0);
    }
    
    public static void limpiarTabla(JTable tabla){
        try {
            DefaultTableModel modelo=(DefaultTableModel) tabla.getModel();
            int filas=tabla.getRowCount();
            for (int i = 0;filas>i; i++) {
                modelo.removeRow(0);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al limpiar la tabla.");
        }
    }

