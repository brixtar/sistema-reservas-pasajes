    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
            int fila = jtVehiculos.getSelectedRow();
            if(fila==-1){
                JOptionPane.showMessageDialog(rootPane, "No se seleccionó ninguna fila");
            } else {
                   int reply = JOptionPane.showConfirmDialog(null,"¿Seguro que desea eliminar el Vehículo?", "ATENCIÓN", JOptionPane.YES_NO_OPTION);
                   if (reply == JOptionPane.YES_OPTION) {
                       String vehiculo_id= jtVehiculos.getValueAt(fila, 0).toString();
                       String descripcion = jtVehiculos.getValueAt(fila, 1).toString();
                       int asientos = Integer.parseInt(jtVehiculos.getValueAt(fila, 2).toString());
                       int estado =1;
                       Vehiculo vehiculo = new Vehiculo(vehiculo_id, descripcion, asientos, estado);
                       vehiculo.eliminar();
                       cargar_tabla();
                   }
                   else {
                      System.out.println("No se eliminó el Vehiculo");
                   }
               }
    }//GEN-LAST:event_btnEliminarActionPerformed

