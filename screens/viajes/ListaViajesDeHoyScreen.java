    private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImprimirActionPerformed
        int fila = PanelViajesScreen.jtViajes.getSelectedRow();
            if(fila==-1){
                JOptionPane.showMessageDialog(rootPane, "No se seleccionó ninguna fila");
            } else {
                ListaPasajeros lista = new ListaPasajeros();
                Object[][] datos= lista.imprimirListaPasajeros(PanelViajesScreen.jtViajes.getValueAt(fila, 0).toString());
                String [] NombresColumnas = {"LISTA PASAJERO ID","VIAJE ID","DNI°","NOMBRE","DOMICILIO","TELEFONO","CANTIDAD","PAGADO"};
                DefaultTableModel modelo = new DefaultTableModel(datos,NombresColumnas);
                ImprimirListaPasajeros comprobante;
                List list=  new ArrayList();
                for (int i=0; i<modelo.getRowCount();i++){  
                    comprobante= new ImprimirListaPasajeros(modelo.getValueAt(i, 2).toString(),modelo.getValueAt(i, 3).toString(),modelo.getValueAt(i, 4).toString(),modelo.getValueAt(i, 5).toString(),modelo.getValueAt(i, 6).toString(),modelo.getValueAt(i, 7).toString());
                    list.add(comprobante);
                    }
                int filas_vacias=25-modelo.getRowCount();
                for (int i=0; i <filas_vacias; i++){ 
                    comprobante= new ImprimirListaPasajeros("", "", "", "", "", "");
                    list.add(comprobante);
                }
                
                String viaje_id= PanelViajesScreen.jtViajes.getValueAt(fila, 0).toString();
                String fecha= PanelViajesScreen.jtViajes.getValueAt(fila, 1).toString();
                String horario= PanelViajesScreen.jtViajes.getValueAt(fila, 2).toString();
                String vehiculo= PanelViajesScreen.jtViajes.getValueAt(fila, 3).toString();
                String conductor= PanelViajesScreen.jtViajes.getValueAt(fila, 4).toString();
                int total= modelo.getRowCount();
                
                try {
               
                        JasperReport reporte = null;

                        String path ="src\\reportes\\listapasajeros.jasper";

                        reporte = (JasperReport) JRLoader.loadObjectFromFile(path);

                        JasperPrint jprint;

                        Map parametros = new HashMap();
                        parametros.put("viaje_id",viaje_id);
                        parametros.put("fecha", fecha);
                        parametros.put("horario", horario);
                        parametros.put("vehiculo", vehiculo);
                        parametros.put("conductor", conductor);

                        jprint =  JasperFillManager.fillReport(reporte, parametros,new JRBeanCollectionDataSource(list));
                        JasperViewer view = new JasperViewer(jprint,false);
                        view.setDefaultCloseOperation(DISPOSE_ON_CLOSE);
                        view.setVisible(true);
                    } catch (JRException ex) {
                        Logger.getLogger(ListaViajesDeHoyScreen.class.getName()).log(Level.SEVERE, null, ex);
                         JOptionPane.showMessageDialog(rootPane, "No se pudo imprimir la lista de pasajeros","ERROR",0);
                    }
                   
            }         
    }//GEN-LAST:event_btnImprimirActionPerformed


